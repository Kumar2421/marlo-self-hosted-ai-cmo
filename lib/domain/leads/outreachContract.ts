/**
 * Shared contract for lead outreach safeguards: the limits, the template ids and the request/response shapes
 * of the outreach API. Pure (types and constants plus two tiny helpers), so the server routes and the
 * compose UI agree on one definition.
 */

/** Most emails one user may send in a rolling UTC day, across all projects. */
export const OUTREACH_DAILY_CAP = 25;
/** Nobody is emailed again by the same user within this many days. */
export const OUTREACH_REPEAT_DAYS = 30;
/** Outreach sends cost one credit per this many emails (rounded up). Tracked during beta, never blocking until billing is on. */
export const OUTREACH_EMAILS_PER_CREDIT = 5;

export const OUTREACH_TEMPLATES = [
  { id: "plain", label: "Plain", description: "Looks like a normal email you typed yourself. Best for cold outreach." },
  { id: "clean", label: "Clean", description: "Simple layout with a clear sign-off and a quiet footer." },
  { id: "card", label: "Card", description: "A light card with your name and company on top." },
] as const;
export type OutreachTemplateId = (typeof OUTREACH_TEMPLATES)[number]["id"];

export function isOutreachTemplateId(value: unknown): value is OutreachTemplateId {
  return OUTREACH_TEMPLATES.some((t) => t.id === value);
}

/** Why a selected lead will not be emailed in this send. */
export type OutreachBlockReason =
  /** The lead has no email address. */
  | "no_email"
  /** The address was generated by Marlo (a pattern guess), not found on a page. Sendable only after the user accepts bounce risk. */
  | "guessed"
  /** The person unsubscribed or replied "stop" to this user. Never sendable. */
  | "unsubscribed"
  /** This user already emailed them within OUTREACH_REPEAT_DAYS. */
  | "recent"
  /** The daily cap is used up for the rest of the selection. */
  | "over_cap";

export type OutreachPlanRequest = { leadIds: string[] };

export type OutreachPlanResponse = {
  /** Leads that will be emailed if the user sends now (guessed ones are included only when `acceptGuessed` was true in the request). */
  sendable: string[];
  blocked: Array<{ leadId: string; reason: OutreachBlockReason }>;
  /** Guessed-address leads that would become sendable if the user accepts bounce risk. */
  guessedIds: string[];
  status: OutreachStatus;
  /** Credits this send would record, for the sendable set. */
  creditCost: number;
};

export type OutreachStatus = {
  dailyCap: number;
  sentToday: number;
  remainingToday: number;
};

export type OutreachSendRequest = {
  leadIds: string[];
  subject: string;
  body: string;
  templateId: OutreachTemplateId;
  /** Include leads whose address Marlo guessed. Defaults to false. */
  acceptGuessed?: boolean;
  /** Send one copy to the user's own address instead of any lead. Not counted against the cap, the repeat rule or credits. */
  test?: boolean;
};

export type OutreachSendResult = {
  results: Array<{ id: string; status: "sent" | "failed" | "skipped"; reason?: OutreachBlockReason; error?: string; threadId?: string; messageId?: string }>;
  status: OutreachStatus;
  creditsRecorded: number;
};

/** Credits recorded for `emails` sends. */
export function outreachCreditCost(emails: number): number {
  return emails <= 0 ? 0 : Math.ceil(emails / OUTREACH_EMAILS_PER_CREDIT);
}

/** Replaces {{name}}, {{company}} and {{title}} the same way on the server and in the preview. */
export function mergeOutreachTags(template: string, lead: { name?: string | null; company?: string | null; title?: string | null }): string {
  return template
    .replaceAll("{{name}}", lead.name || "")
    .replaceAll("{{company}}", lead.company || "")
    .replaceAll("{{title}}", lead.title || "");
}
